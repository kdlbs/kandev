// Package opencodeplugin owns the Kandev-supplied server plugin for supported
// OpenCode v2 runtimes: the embedded artifact, the private launch host, the
// versioned behavior protocol, and typed observation receivers.
package opencodeplugin

import (
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io/fs"
	"path"
)

//go:embed assets/index.mjs assets/package.json assets/artifact.json
var artifactFiles embed.FS

// ArtifactEntrypoint is the immutable plugin entry file inside the artifact
// directory. OpenCode resolves a local directory through its package manifest.
const ArtifactEntrypoint = "index.mjs"

// ArtifactPackageFile is the minimal package manifest OpenCode reads to resolve
// the local plugin directory.
const ArtifactPackageFile = "package.json"

// ArtifactManifestFile records the exact generated bytes.
const ArtifactManifestFile = "artifact.json"

// ArtifactManifest describes one deterministic generated artifact.
type ArtifactManifest struct {
	FormatVersion int    `json:"formatVersion"`
	Entrypoint    string `json:"entrypoint"`
	SHA256        string `json:"sha256"`
	Bytes         int    `json:"bytes"`
}

// Artifact returns the checked-in generated plugin directory.
func Artifact() fs.FS {
	return artifactFiles
}

// ArtifactManifestValue decodes and validates the checked manifest.
func ArtifactManifestValue() (ArtifactManifest, error) {
	raw, err := artifactFiles.ReadFile(path.Join("assets", ArtifactManifestFile))
	if err != nil {
		return ArtifactManifest{}, fmt.Errorf("read embedded artifact manifest: %w", err)
	}
	var manifest ArtifactManifest
	if err := json.Unmarshal(raw, &manifest); err != nil {
		return ArtifactManifest{}, fmt.Errorf("decode embedded artifact manifest: %w", err)
	}
	if manifest.FormatVersion != 1 || manifest.Entrypoint != ArtifactEntrypoint || len(manifest.SHA256) != 64 {
		return ArtifactManifest{}, fmt.Errorf("embedded artifact manifest is incomplete")
	}
	return manifest, nil
}

// ArtifactBytes returns the exact entrypoint bytes and their SHA-256.
func ArtifactBytes() ([]byte, string, error) {
	raw, err := artifactFiles.ReadFile(path.Join("assets", ArtifactEntrypoint))
	if err != nil {
		return nil, "", fmt.Errorf("read embedded plugin entrypoint: %w", err)
	}
	sum := sha256.Sum256(raw)
	return raw, hex.EncodeToString(sum[:]), nil
}
