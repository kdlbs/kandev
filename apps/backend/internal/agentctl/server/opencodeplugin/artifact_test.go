func TestStageArtifactRejectsSymlinkedEntrypoint(t *testing.T) {
	root := t.TempDir()
	dir, err := StageArtifact(root)
	if err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(root, "entrypoint-target.mjs")
	raw, err := artifactFiles.ReadFile("assets/" + ArtifactEntrypoint)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, raw, 0o600); err != nil {
		t.Fatal(err)
	}
	entrypoint := filepath.Join(dir, ArtifactEntrypoint)
	if err := os.Remove(entrypoint); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, entrypoint); err != nil {
		t.Skipf("symlinks are unavailable on this platform: %v", err)
	}
	if _, err := StageArtifact(root); err != nil {
		t.Fatalf("StageArtifact() error = %v", err)
	}
	info, err := os.Lstat(entrypoint)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		t.Fatalf("staged entrypoint mode = %v, want regular file", info.Mode())
	}
}

func TestStageArtifactRejectsSymlinkedDirectory(t *testing.T) {
	root := t.TempDir()
	manifest, err := ArtifactManifestValue()
	if err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(root, "alternate-artifact")
	if err := os.MkdirAll(target, 0o700); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{ArtifactEntrypoint, ArtifactPackageFile, ArtifactManifestFile} {
		raw, readErr := artifactFiles.ReadFile("assets/" + name)
		if readErr != nil {
			t.Fatal(readErr)
		}
		if writeErr := os.WriteFile(filepath.Join(target, name), raw, 0o600); writeErr != nil {
			t.Fatal(writeErr)
		}
	}
	link := filepath.Join(root, manifest.SHA256)
	if err := os.Symlink(target, link); err != nil {
		t.Skipf("symlinks are unavailable on this platform: %v", err)
	}
	staged, err := StageArtifact(root)
	if err != nil {
		t.Fatalf("StageArtifact() error = %v", err)
	}
	info, err := os.Lstat(staged)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		t.Fatalf("staged directory mode = %v, want real directory", info.Mode())
	}
}
