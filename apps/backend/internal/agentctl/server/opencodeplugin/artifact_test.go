func TestArtifactMatchesManifest(t *testing.T) {
	manifest, err := ArtifactManifestValue()
	if err != nil {
		t.Fatalf("ArtifactManifestValue() error = %v", err)
	}
	raw, hash, err := ArtifactBytes()
	if err != nil {
		t.Fatalf("ArtifactBytes() error = %v", err)
	}
	if len(raw) != manifest.Bytes {
		t.Fatalf("artifact bytes = %d, manifest = %d", len(raw), manifest.Bytes)
	}
	if hash != manifest.SHA256 {
		t.Fatalf("artifact hash = %s, manifest = %s", hash, manifest.SHA256)
	}
	if !bytes.HasPrefix(raw, []byte("// Generated by @kandev/opencode-plugin.")) {
		t.Fatal("artifact is not the generated Kandev plugin")
	}
	var pkg struct {
		Type    string            `json:"type"`
		Exports map[string]string `json:"exports"`
	}
	pkgRaw, err := artifactFiles.ReadFile("assets/" + ArtifactPackageFile)
	if err != nil {
		t.Fatalf("read artifact package: %v", err)
	}
	if err := json.Unmarshal(pkgRaw, &pkg); err != nil {
		t.Fatalf("decode artifact package: %v", err)
	}
	if pkg.Type != "module" || pkg.Exports["."] != "./index.mjs" {
		t.Fatalf("artifact package = %#v, want module entrypoint", pkg)
	}
}

func TestArtifactContainsOnlyReviewedFiles(t *testing.T) {
	entries, err := fs.ReadDir(artifactFiles, "assets")
	if err != nil {
		t.Fatalf("read embedded assets: %v", err)
	}
	names := make(map[string]bool, len(entries))
	for _, entry := range entries {
		names[entry.Name()] = true
	}
	for _, want := range []string{ArtifactEntrypoint, ArtifactPackageFile, ArtifactManifestFile} {
		if !names[want] {
			t.Fatalf("embedded artifact missing %q", want)
		}
	}
	if len(names) != 3 {
		t.Fatalf("embedded artifact has unexpected files: %v", names)
	}
}

func TestArtifactIsDependencyFree(t *testing.T) {
	raw, _, err := ArtifactBytes()
	if err != nil {
		t.Fatalf("ArtifactBytes() error = %v", err)
	}
	for _, forbidden := range [][]byte{
		[]byte("require("),
		[]byte("@opencode/plugin"),
		[]byte("effect/"),
	} {
		if bytes.Contains(raw, forbidden) {
			t.Fatalf("artifact contains forbidden runtime import %q", forbidden)
		}
	}
}

func TestStageArtifactIsAtomicAndVerified(t *testing.T) {
	root := t.TempDir()
	manifest, err := ArtifactManifestValue()
	if err != nil {
		t.Fatal(err)
	}
	dir, err := StageArtifact(root)
	if err != nil {
		t.Fatalf("StageArtifact() error = %v", err)
	}
	if filepath.Base(dir) != manifest.SHA256 {
		t.Fatalf("artifact dir = %q, want content hash %q", dir, manifest.SHA256)
	}
	raw, err := os.ReadFile(filepath.Join(dir, ArtifactEntrypoint))
	if err != nil {
		t.Fatalf("read staged artifact: %v", err)
	}
	sum := sha256.Sum256(raw)
	if hex.EncodeToString(sum[:]) != manifest.SHA256 {
		t.Fatal("staged artifact bytes do not match the manifest")
	}
	again, err := StageArtifact(root)
	if err != nil {
		t.Fatalf("repeated StageArtifact() error = %v", err)
	}
	if again != dir {
		t.Fatalf("repeated staging = %q, want %q", again, dir)
	}
}

func TestStageArtifactReplacesTamperedContent(t *testing.T) {
	root := t.TempDir()
	manifest, err := ArtifactManifestValue()
	if err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(root, manifest.SHA256)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, ArtifactEntrypoint), []byte("tampered"), 0o600); err != nil {
		t.Fatal(err)
	}
	staged, err := StageArtifact(root)
	if err != nil {
		t.Fatalf("StageArtifact() error = %v", err)
	}
	raw, err := os.ReadFile(filepath.Join(staged, ArtifactEntrypoint))
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(raw)
	if hex.EncodeToString(sum[:]) != manifest.SHA256 {
		t.Fatal("StageArtifact() reused tampered content")
	}
}

