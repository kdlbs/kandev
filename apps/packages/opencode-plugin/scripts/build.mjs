import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../../..");
const distDir = join(packageRoot, "dist");
const assetsDir = join(repoRoot, "apps/backend/internal/agentctl/server/opencodeplugin/assets");
const manifestPath = join(assetsDir, "artifact.json");
const check = process.argv.includes("--check");
const BUILD_VERSION = 1;

async function main() {
  const output = await bundle();
  const hash = sha256(output);
  const manifest = {
    formatVersion: BUILD_VERSION,
    entrypoint: "index.mjs",
    sha256: hash,
    bytes: Buffer.byteLength(output, "utf8"),
  };
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  const packageManifest = {
    name: "kandev-opencode-plugin",
    version: "0.1.0",
    private: true,
    type: "module",
    exports: { ".": "./index.mjs" },
  };
  const packageText = `${JSON.stringify(packageManifest, null, 2)}\n`;

  if (check) {
    const [checkedOutput, checkedManifest, checkedPackage] = await Promise.all([
      readFile(join(assetsDir, "index.mjs"), "utf8").catch(() => ""),
      readFile(manifestPath, "utf8").catch(() => ""),
      readFile(join(assetsDir, "package.json"), "utf8").catch(() => ""),
    ]);
    if (
      checkedOutput !== output ||
      checkedManifest !== manifestText ||
      checkedPackage !== packageText
    ) {
      throw new Error(
        "generated OpenCode plugin artifact is stale; run pnpm --filter @kandev/opencode-plugin build",
      );
    }
    console.log(`opencode plugin artifact verified: sha256=${hash}`);
    return;
  }

  await rm(distDir, { recursive: true, force: true });
  await mkdir(distDir, { recursive: true });
  await writeFile(join(distDir, "index.mjs"), output);
  await writeFile(join(distDir, "package.json"), packageText);
  await writeFile(join(distDir, "artifact.json"), manifestText);

  await mkdir(assetsDir, { recursive: true });
  await writeFile(join(assetsDir, "index.mjs"), output);
  await writeFile(join(assetsDir, "package.json"), packageText);
  await writeFile(manifestPath, manifestText);
  console.log(`opencode plugin artifact written: sha256=${hash} bytes=${manifest.bytes}`);
}

async function bundle() {
  const result = await build({
    entryPoints: [join(packageRoot, "src/index.ts")],
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    target: "node20",
    charset: "utf8",
    legalComments: "none",
    banner: {
      js: "// Generated by @kandev/opencode-plugin. Do not edit by hand.",
    },
  });
  if (result.outputFiles.length !== 1) {
    throw new Error(`expected one bundled output, got ${result.outputFiles.length}`);
  }
  return result.outputFiles[0]?.text ?? "";
}

function sha256(value) {
  return createHash("sha256").update(value, "utf8").digest("hex");
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : "opencode plugin build failed");
  process.exitCode = 1;
});
